def scale_wiki_value(value: float, stat: str) -> int:
    low, high = CARD_SURVIVAL_STAT_RANGES[stat]
    return max(0, min(PLAYER_STAT_RANGE, round((value - low) * PLAYER_STAT_RANGE / (high - low))))


def scale_wiki_delta(delta: float, stat: str) -> int:
    low, high = CARD_SURVIVAL_STAT_RANGES[stat]
    return max(0, min(PLAYER_STAT_RANGE, round(delta * PLAYER_STAT_RANGE / (high - low))))


